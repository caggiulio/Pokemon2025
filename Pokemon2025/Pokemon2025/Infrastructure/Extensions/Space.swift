import Foundation

public extension CGFloat {
  /// The micro small space, i.e. 2
  static let micro: CGFloat = 2

  /// The extra extra small space, i.e. 4
  static let xxSmall: CGFloat = 4

  /// The extra small space, i.e. 8
  static let xSmall: CGFloat = 8

  /// The small space, i.e. 16
  static let small: CGFloat = 16

  /// The medium space, i.e. 32
  static let medium: CGFloat = 32

  /// The large space, i.e. 64
  static let large: CGFloat = 64

  /// The extra large space, i.e. 128
  static let xLarge: CGFloat = 128

  /// The extra extra large space, i.e. 256
  static let xxLarge: CGFloat = 256
}
